function base(
  setId: string,
  id: string,
  topicId: string,
  part: "A" | "B" | "C",
  points: number,
  type: Question["type"],
  level: Difficulty,
): Question {
  return {
    questionId: `${setId}-${id}`,
    setId,
    topicId,
    chapterId: lessonById[topicId].chapterId,
    part,
    points,
    type,
    difficulty: level,
    question: "",
    english: "",
    correctAnswer: "",
    explanation: "",
    source,
    sourcePage: null,
  };
}
function longQuestion(
  setId: string,
  id: string,
  topicId: string,
  title: string,
  english: string,
  level: Difficulty,
  subs: {
    q: string;
    en: string;
    answer: number | string;
    explanation: string;
    points: number;
    tolerance?: number;
    rubric?: string[];
  }[],
): Question {
  const children = subs.map((s, i) => ({
    ...base(
      setId,
      `${id}-${i + 1}`,
      topicId,
      "C",
      s.points,
      typeof s.answer === "number" ? "numeric" : "written",
      level,
    ),
    question: s.q,
    english: s.en,
    correctAnswer: s.answer,
    explanation: s.explanation,
    tolerance: s.tolerance ?? 0.00001,
    rubric: s.rubric,
  }));
  return {
    ...base(
      setId,
      id,
      topicId,
      "C",
      children.reduce((s, q) => s + q.points, 0),
      "written",
      level,
    ),
    question: title,
    english,
    correctAnswer: "소문항 모범답안 참고",
    explanation: "각 소문항은 표시된 배점과 기준으로 별도 채점한다.",
    subquestions: children,
  };
}
